#!/usr/bin/env bash
# Install rules and skills for Claude Code, and the rules for Cursor.
# Adds and overwrites; never deletes. Skills renamed or removed from this
# repository must be deleted from ~/.claude/skills/ by hand, because that
# directory also holds skills that do not come from here.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
claude_dir="$HOME/.claude"
cursor_dir="$HOME/.cursor"

mkdir -p "$claude_dir/rules" "$claude_dir/skills"
cp -R "$repo/rules/." "$claude_dir/rules/"
cp -R "$repo/skills/." "$claude_dir/skills/"
echo "Claude Code: rules and skills copied to $claude_dir"

if [[ ! -e "$claude_dir/settings.json" ]]; then
  cp "$repo/settings.json" "$claude_dir/settings.json"
  echo "Claude Code: settings.json installed"
else
  echo "Claude Code: settings.json exists, not touched — merge by hand"
fi

# Cursor reads skills from ~/.claude/skills itself. Rules need a .mdc copy
# with frontmatter; whether Cursor auto-loads ~/.cursor/rules is not
# documented, so check in Cursor that they apply.
if [[ -d "$cursor_dir" ]]; then
  mkdir -p "$cursor_dir/rules"
  for rule in "$repo"/rules/*.md; do
    name="$(basename "$rule" .md)"
    {
      printf -- '---\ndescription: %s\nalwaysApply: true\n---\n\n' "$name"
      printf '<!-- Generated by scripts/install.sh from rules/%s.md. Do not edit. -->\n\n' "$name"
      cat "$rule"
    } > "$cursor_dir/rules/$name.mdc"
  done
  echo "Cursor: rules written to $cursor_dir/rules"
else
  echo "Cursor: $cursor_dir not found, skipped"
fi
